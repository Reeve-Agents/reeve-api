import { findCard, type Rulebook } from "@reeve/core";

/** Deliberate defects, used only to demonstrate that the Auditor catches Builder mistakes. */
export type InjectedBug = "ignore_tenure_grace";

/** The Builder's internal understanding of the rulebook (what it believes the rules are). */
export interface BuilderModel {
  invoiceDay: number;
  reminderDays: number[];
  lateFee: { days: number; percent: number; basis: "rent" | "outstanding"; grace: { minMonths: number; extraDays: number } | null } | null;
  noticeDays: number | null;
  overpayment: "credit_next_invoice" | "refund_with_approval";
  refundApprovalAbove: number | null;
  revenue: { target: number; basis: "collected" | "invoiced"; alertDay: number } | null;
  sources: Record<string, string>;
}

export function modelFromRulebook(rb: Rulebook, bugs: InjectedBug[] = []): BuilderModel {
  const inv = findCard(rb, "invoice_schedule");
  const reminders = rb.cards.filter((c) => c.type === "reminder").flatMap((c) => (c.type === "reminder" ? c.days_after_due : []));
  const fee = findCard(rb, "late_fee");
  const notice = findCard(rb, "notice");
  const over = findCard(rb, "overpayment");
  const approval = findCard(rb, "approval_threshold");
  const kpi = findCard(rb, "revenue_target");
  const sources: Record<string, string> = {};
  for (const c of rb.cards) sources[c.type] = `${c.id}: ${c.source_quote}`;
  return {
    invoiceDay: inv?.day_of_month ?? 1,
    reminderDays: [...new Set(reminders)].filter((d) => d > 0).sort((a, b) => a - b),
    lateFee: fee
      ? {
          days: fee.days_after_due,
          percent: fee.percent,
          basis: fee.basis,
          grace:
            fee.tenure_grace && !bugs.includes("ignore_tenure_grace")
              ? { minMonths: fee.tenure_grace.min_months, extraDays: fee.tenure_grace.extra_days }
              : null,
        }
      : null,
    noticeDays: notice?.days_after_due ?? null,
    overpayment: over?.policy ?? "credit_next_invoice",
    refundApprovalAbove: approval?.refund_above ?? null,
    revenue: kpi ? { target: kpi.monthly_target, basis: kpi.basis, alertDay: kpi.alert_day } : null,
    sources,
  };
}

const py = (v: number | string | null): string => (v === null ? "None" : typeof v === "string" ? JSON.stringify(v) : String(v));
const comment = (m: BuilderModel, type: string) => (m.sources[type] ? `  # ${m.sources[type]!.replace(/\s+/g, " ").slice(0, 90)}` : "");

/** Compile the Builder's model into an executable Python rules module for reeve_runtime.engine. */
export function generateRulesPy(m: BuilderModel, rulebookHash: string): string {
  const fee = m.lateFee;
  const graceLine = fee?.grace
    ? `    if GRACE_MIN_MONTHS is not None and _tenure_months(tenant.move_in, today) >= GRACE_MIN_MONTHS:\n        days = days + GRACE_EXTRA_DAYS\n`
    : "";
  return `"""Generated by Reeve Builder from rulebook ${rulebookHash.slice(0, 16)}. Do not edit by hand."""
from __future__ import annotations

import datetime as dt

INVOICE_DAY = ${m.invoiceDay}${comment(m, "invoice_schedule")}
REMINDER_DAYS = (${m.reminderDays.join(", ")}${m.reminderDays.length === 1 ? "," : ""})${comment(m, "reminder")}
LATE_FEE_DAYS = ${py(fee?.days ?? null)}${comment(m, "late_fee")}
LATE_FEE_PERCENT = ${py(fee ? Number(fee.percent.toFixed(4)) : null)}
LATE_FEE_BASIS = ${py(fee?.basis ?? "rent")}
GRACE_MIN_MONTHS = ${py(fee?.grace?.minMonths ?? null)}
GRACE_EXTRA_DAYS = ${py(fee?.grace?.extraDays ?? 0)}
NOTICE_DAYS = ${py(m.noticeDays)}${comment(m, "notice")}
OVERPAYMENT_POLICY = ${py(m.overpayment)}${comment(m, "overpayment")}
REFUND_APPROVAL_ABOVE = ${py(m.refundApprovalAbove)}${comment(m, "approval_threshold")}
REVENUE_TARGET = ${py(m.revenue?.target ?? null)}${comment(m, "revenue_target")}
REVENUE_BASIS = ${py(m.revenue?.basis ?? "collected")}
KPI_ALERT_DAY = ${py(m.revenue?.alertDay ?? null)}


def _tenure_months(move_in: dt.date, today: dt.date) -> int:
    months = (today.year - move_in.year) * 12 + (today.month - move_in.month)
    if today.day < move_in.day:
        months -= 1
    return max(months, 0)


def issues_invoice_today(today: dt.date) -> bool:
    return today.day == INVOICE_DAY


def reminder_due(days_overdue: int) -> bool:
    return days_overdue in REMINDER_DAYS


def late_fee_threshold(tenant, today: dt.date):
    if LATE_FEE_DAYS is None:
        return None
    days = LATE_FEE_DAYS
${graceLine}    return days


def late_fee_amount(invoice, tenant, days_overdue: int, today: dt.date) -> int:
    threshold = late_fee_threshold(tenant, today)
    if threshold is None or invoice.fee_charged:
        return 0
    if days_overdue >= threshold:
        base = tenant.rent if LATE_FEE_BASIS == "rent" else invoice.outstanding_principal
        return int(round(base * LATE_FEE_PERCENT / 100))
    return 0


def notice_due(days_overdue: int) -> bool:
    return NOTICE_DAYS is not None and days_overdue >= NOTICE_DAYS


def handle_overpayment(amount: int, tenant):
    if OVERPAYMENT_POLICY == "credit_next_invoice":
        return ("credit", amount, False)
    needs_approval = REFUND_APPROVAL_ABOVE is not None and amount > REFUND_APPROVAL_ABOVE
    return ("refund_request", amount, needs_approval)


def kpi_check_today(today: dt.date) -> bool:
    return REVENUE_TARGET is not None and today.day == KPI_ALERT_DAY


def kpi_alert(collected_mtd: int, invoiced_mtd: int, today: dt.date) -> bool:
    value = collected_mtd if REVENUE_BASIS == "collected" else invoiced_mtd
    return value < REVENUE_TARGET
`;
}

/** The Builder's own unit tests. They test the Builder's understanding, which is exactly why an independent Auditor is still needed. */
export function generateBuilderTestsPy(m: BuilderModel): string {
  const fee = m.lateFee;
  const tests: string[] = [];
  tests.push(`    def test_invoice_day(self):
        self.assertTrue(rules.issues_invoice_today(dt.date(2026, 11, ${m.invoiceDay})))
        self.assertFalse(rules.issues_invoice_today(dt.date(2026, 11, ${m.invoiceDay === 28 ? 27 : m.invoiceDay + 1})))`);
  if (m.reminderDays.length) {
    tests.push(`    def test_reminder_days(self):
        for d in (${m.reminderDays.join(", ")},):
            self.assertTrue(rules.reminder_due(d))
        self.assertFalse(rules.reminder_due(${Math.max(...m.reminderDays) + 1}))`);
  }
  if (fee) {
    tests.push(`    def test_late_fee_starts_on_day(self):
        tenant = T(rent=1000000, move_in=dt.date(2026, 10, 1))
        today = dt.date(2026, 11, 20)
        self.assertEqual(rules.late_fee_amount(I(), tenant, ${fee.days - 1}, today), 0)
        self.assertEqual(rules.late_fee_amount(I(), tenant, ${fee.days}, today), ${Math.round((1000000 * fee.percent) / 100)})`);
    tests.push(`    def test_late_fee_only_once(self):
        tenant = T(rent=1000000, move_in=dt.date(2026, 10, 1))
        self.assertEqual(rules.late_fee_amount(I(fee_charged=True), tenant, ${fee.days + 1}, dt.date(2026, 11, 20)), 0)`);
    if (fee.grace) {
      tests.push(`    def test_long_term_tenant_grace(self):
        veteran = T(rent=1000000, move_in=dt.date(2024, 1, 1))
        today = dt.date(2026, 11, 20)
        self.assertEqual(rules.late_fee_amount(I(), veteran, ${fee.days}, today), 0)
        self.assertGreater(rules.late_fee_amount(I(), veteran, ${fee.days + fee.grace.extraDays}, today), 0)`);
    }
  }
  if (m.noticeDays !== null) {
    tests.push(`    def test_notice(self):
        self.assertFalse(rules.notice_due(${m.noticeDays - 1}))
        self.assertTrue(rules.notice_due(${m.noticeDays}))`);
  }
  tests.push(`    def test_overpayment_policy(self):
        kind, amount, _ = rules.handle_overpayment(100, T(rent=1, move_in=dt.date(2026, 1, 1)))
        self.assertEqual(kind, ${py(m.overpayment === "credit_next_invoice" ? "credit" : "refund_request")})
        self.assertEqual(amount, 100)`);

  return `"""Builder's own tests for rules.py (generated)."""
import datetime as dt
import unittest

import rules


class T:
    def __init__(self, rent, move_in):
        self.rent = rent
        self.move_in = move_in


class I:
    def __init__(self, fee_charged=False, outstanding_principal=1000000):
        self.fee_charged = fee_charged
        self.outstanding_principal = outstanding_principal


class BuilderTests(unittest.TestCase):
${tests.join("\n\n")}


if __name__ == "__main__":
    unittest.main()
`;
}
