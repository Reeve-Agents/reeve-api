import { findCard, type Rulebook } from "@reeve/core";

/** Deliberate defect for the minimarket pack: the Builder forgets "never below cost". */
export type StockBug = "ignore_markdown_floor";

/** The Builder's understanding of a minimarket rulebook. */
export interface StockModel {
  reorderBelow: number;
  orderUpTo: number;
  supplier: string;
  backup: { supplier: string; lateDays: number } | null;
  markdowns: { days: number; percent: number }[];
  floor: "cost" | null;
  slowMoverDays: number | null;
  poApprovalAbove: number | null;
  kpi: { maxValue: number; windowDays: number; weekday: number } | null;
  sources: Record<string, string>;
}

export function stockModelFromRulebook(rb: Rulebook, bugs: StockBug[] = []): StockModel {
  const reorder = findCard(rb, "reorder_point");
  const fallback = findCard(rb, "supplier_fallback");
  const floor = findCard(rb, "markdown_floor");
  const slow = findCard(rb, "slow_mover_stop");
  const po = findCard(rb, "po_approval_threshold");
  const kpi = findCard(rb, "expiring_value_limit");
  const markdowns = rb.cards
    .flatMap((c) => (c.type === "expiry_markdown" ? [{ days: c.days_before_expiry, percent: c.percent }] : []))
    .sort((a, b) => b.days - a.days);
  const sources: Record<string, string> = {};
  for (const c of rb.cards) sources[c.type] = [sources[c.type], `${c.id}: ${c.source_quote}`].filter(Boolean).join(" | ");
  return {
    reorderBelow: reorder?.below_units ?? 0,
    orderUpTo: reorder?.order_up_to_units ?? 0,
    supplier: reorder?.supplier ?? "A",
    backup: fallback ? { supplier: fallback.backup_supplier, lateDays: fallback.late_days } : null,
    markdowns,
    floor: floor && !bugs.includes("ignore_markdown_floor") ? floor.floor : null,
    slowMoverDays: slow?.no_sale_days ?? null,
    poApprovalAbove: po?.po_above ?? null,
    kpi: kpi ? { maxValue: kpi.max_value, windowDays: kpi.window_days, weekday: kpi.check_weekday } : null,
    sources,
  };
}

const py = (v: number | string | null): string => (v === null ? "None" : typeof v === "string" ? JSON.stringify(v) : String(v));
const comment = (m: StockModel, type: string) => (m.sources[type] ? `  # ${m.sources[type]!.replace(/\s+/g, " ").slice(0, 90)}` : "");

/** Compile the Builder's model into a rules module for reeve_runtime.stock_engine. */
export function generateStockRulesPy(m: StockModel, rulebookHash: string): string {
  const steps = m.markdowns.map((s) => `(${s.days}, ${s.percent})`).join(", ");
  return `"""Generated by Reeve Builder from rulebook ${rulebookHash.slice(0, 16)}. Do not edit by hand."""
from __future__ import annotations

import datetime as dt

REORDER_BELOW = ${m.reorderBelow}${comment(m, "reorder_point")}
ORDER_UP_TO = ${m.orderUpTo}
DEFAULT_SUPPLIER = ${py(m.supplier)}
BACKUP_SUPPLIER = ${py(m.backup?.supplier ?? null)}${comment(m, "supplier_fallback")}
SWITCH_AFTER_LATE_DAYS = ${py(m.backup?.lateDays ?? null)}
MARKDOWN_STEPS = (${steps}${m.markdowns.length === 1 ? "," : ""})${comment(m, "expiry_markdown")}
MARKDOWN_FLOOR = ${py(m.floor)}${comment(m, "markdown_floor")}
SLOW_MOVER_DAYS = ${py(m.slowMoverDays)}${comment(m, "slow_mover_stop")}
PO_APPROVAL_ABOVE = ${py(m.poApprovalAbove)}${comment(m, "po_approval_threshold")}
EXPIRING_WINDOW_DAYS = ${py(m.kpi?.windowDays ?? null)}${comment(m, "expiring_value_limit")}
EXPIRING_VALUE_LIMIT = ${py(m.kpi?.maxValue ?? null)}
KPI_CHECK_WEEKDAY = ${py(m.kpi?.weekday ?? null)}


def default_supplier() -> str:
    return DEFAULT_SUPPLIER


def backup_supplier():
    return BACKUP_SUPPLIER


def below_reorder_point(on_hand: int, on_order: int) -> bool:
    return on_hand + on_order < REORDER_BELOW


def is_slow_mover(days_since_sale: int) -> bool:
    return SLOW_MOVER_DAYS is not None and days_since_sale >= SLOW_MOVER_DAYS


def reorder_due(on_hand: int, on_order: int, days_since_sale: int) -> bool:
    if is_slow_mover(days_since_sale):
        return False
    return below_reorder_point(on_hand, on_order)


def order_quantity(on_hand: int, on_order: int) -> int:
    return max(ORDER_UP_TO - on_hand - on_order, 0)


def po_needs_approval(value: int) -> bool:
    return PO_APPROVAL_ABOVE is not None and value > PO_APPROVAL_ABOVE


def switch_supplier(days_late: int) -> bool:
    return SWITCH_AFTER_LATE_DAYS is not None and days_late >= SWITCH_AFTER_LATE_DAYS


def markdown_percent(days_to_expiry: int) -> int:
    percent = 0
    for days, off in MARKDOWN_STEPS:
        if days_to_expiry <= days:
            percent = max(percent, off)
    return percent


def markdown_price(price: int, cost: int, percent: int) -> int:
    new = int(round(price * (100 - percent) / 100))
    if MARKDOWN_FLOOR == "cost":
        new = max(new, cost)
    return new


def counts_as_expiring(days_to_expiry: int) -> bool:
    return EXPIRING_WINDOW_DAYS is not None and 0 <= days_to_expiry <= EXPIRING_WINDOW_DAYS


def kpi_check_today(today: dt.date) -> bool:
    return EXPIRING_VALUE_LIMIT is not None and today.weekday() == KPI_CHECK_WEEKDAY


def kpi_alert(value: int) -> bool:
    return value > EXPIRING_VALUE_LIMIT
`;
}

/** The Builder's own tests: they check its understanding, which is why the Auditor still checks the rulebook. */
export function generateStockBuilderTestsPy(m: StockModel): string {
  const t: string[] = [];
  t.push(`    def test_reorder_point(self):
        self.assertTrue(rules.below_reorder_point(${m.reorderBelow - 1}, 0))
        self.assertFalse(rules.below_reorder_point(${m.reorderBelow}, 0))
        self.assertTrue(rules.reorder_due(${m.reorderBelow - 1}, 0, 0))`);
  t.push(`    def test_order_up_to(self):
        self.assertEqual(rules.order_quantity(${m.reorderBelow - 1}, 0), ${m.orderUpTo - m.reorderBelow + 1})
        self.assertEqual(rules.default_supplier(), ${py(m.supplier)})`);
  if (m.backup) {
    t.push(`    def test_supplier_fallback(self):
        self.assertFalse(rules.switch_supplier(${m.backup.lateDays - 1}))
        self.assertTrue(rules.switch_supplier(${m.backup.lateDays}))
        self.assertEqual(rules.backup_supplier(), ${py(m.backup.supplier)})`);
  }
  if (m.markdowns.length) {
    const lines = m.markdowns.map((s) => `        self.assertEqual(rules.markdown_percent(${s.days}), ${s.percent})`).join("\n");
    t.push(`    def test_markdown_steps(self):
${lines}
        self.assertEqual(rules.markdown_percent(${m.markdowns[0]!.days + 1}), 0)`);
  }
  if (m.floor) {
    t.push(`    def test_markdown_floor(self):
        self.assertEqual(rules.markdown_price(12000, 10000, 50), 10000)`);
  }
  if (m.slowMoverDays !== null) {
    t.push(`    def test_slow_mover(self):
        self.assertFalse(rules.is_slow_mover(${m.slowMoverDays - 1}))
        self.assertTrue(rules.is_slow_mover(${m.slowMoverDays}))
        self.assertFalse(rules.reorder_due(0, 0, ${m.slowMoverDays}))`);
  }
  if (m.poApprovalAbove !== null) {
    t.push(`    def test_po_approval(self):
        self.assertFalse(rules.po_needs_approval(${m.poApprovalAbove}))
        self.assertTrue(rules.po_needs_approval(${m.poApprovalAbove + 1}))`);
  }
  if (m.kpi) {
    t.push(`    def test_expiring_value_kpi(self):
        self.assertFalse(rules.kpi_alert(${m.kpi.maxValue}))
        self.assertTrue(rules.kpi_alert(${m.kpi.maxValue + 1}))
        self.assertTrue(rules.counts_as_expiring(${m.kpi.windowDays}))
        self.assertFalse(rules.counts_as_expiring(${m.kpi.windowDays + 1}))
        monday = dt.date(2026, 11, 2)
        self.assertTrue(rules.kpi_check_today(monday + dt.timedelta(days=${m.kpi.weekday})))`);
  }
  return `"""Builder's own tests for rules.py (generated, minimarket pack)."""
import datetime as dt
import unittest

import rules


class BuilderTests(unittest.TestCase):
${t.join("\n\n")}


if __name__ == "__main__":
    unittest.main()
`;
}
